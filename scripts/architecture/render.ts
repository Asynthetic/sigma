import type { ArchitectureGraph } from "./graph.ts";
import type { GraphEdge } from "./types.ts";

export const CONTEXT_MAX_BYTES = 16 * 1024;
export const OUTPUT_DIRECTORY = "docs/architecture";

function mermaidId(id: string) {
  return `n_${id.replaceAll(".", "_")}`;
}

function mermaidLabel(label: string) {
  return label.replace(/["#<>|&\r\n]/g, (char) => `#${char.charCodeAt(0)};`);
}

function nodeLine(id: string, label: string) {
  return `  ${mermaidId(id)}["${mermaidLabel(label)}"]`;
}

function edgeLine({
  from,
  to,
  type,
  provenance,
}: Pick<GraphEdge, "from" | "to" | "provenance"> & { type: string }) {
  const label = type.replaceAll("_", " ");
  const arrow =
    provenance === "verified" ? `-- ${label} -->` : `-. ${label} .->`;
  return `  ${mermaidId(from)} ${arrow} ${mermaidId(to)}`;
}

function diagram(title: string, lines: string[], footer: string[]) {
  return [
    `# ${title}`,
    "",
    "<!-- Generated by pnpm architecture:generate -->",
    "",
    "Solid arrows show verified source relationships. Dotted arrows show declared relationships.",
    "",
    "```mermaid",
    "flowchart LR",
    ...lines,
    "```",
    "",
    ...footer,
    "",
  ].join("\n");
}

function labelFor(graph: ArchitectureGraph, id: string) {
  return graph.nodes[id].label ?? id;
}

function renderOverview(graph: ArchitectureGraph) {
  const boundaries = new Map<string, string>();
  for (const edge of graph.edges) {
    const from = graph.nodes[edge.from].subsystem;
    const to = graph.nodes[edge.to].subsystem;
    if (from === to) continue;
    boundaries.set(
      `${from}:${to}:${edge.provenance}`,
      edgeLine({
        from,
        to,
        provenance: edge.provenance,
        type: edge.provenance,
      }),
    );
  }
  const subsystems = Object.entries(graph.subsystems);
  return diagram(
    "Sigma architecture",
    [
      ...subsystems.map(([id, title]) => nodeLine(id, title)),
      ...[...boundaries.values()].sort(),
    ],
    [
      ...subsystems.map(([id, title]) => `- [${title}](${id}.md)`),
      "- [Canonical graph](graph.json)",
      "- [Agent context](agent-context.json)",
      "- [Maintenance and scope](README.md)",
    ],
  );
}

function renderSubsystem(graph: ArchitectureGraph, subsystem: string) {
  const members = new Set(
    Object.keys(graph.nodes).filter(
      (id) => graph.nodes[id].subsystem === subsystem,
    ),
  );
  const edges = graph.edges.filter(
    (edge) =>
      members.has(edge.from) ||
      members.has(edge.to) ||
      (subsystem === "ipc" && edge.type === "invokes"),
  );
  const visible = new Set([
    ...members,
    ...edges.flatMap(({ from, to }) => [from, to]),
  ]);
  const commandEdges = edges.filter((edge) => "commands" in edge);
  return diagram(
    graph.subsystems[subsystem],
    [
      ...[...visible].sort().map((id) => nodeLine(id, labelFor(graph, id))),
      ...edges.map(edgeLine),
    ],
    [
      ...(commandEdges.length
        ? [
            "## IPC commands",
            "",
            ...commandEdges.map(
              (edge) =>
                `- \`${labelFor(graph, edge.from)}\` → \`${labelFor(graph, edge.to)}\` (${edge.type}) — ${edge.commands.map((name) => `\`${name}\``).join(", ")}`,
            ),
            "",
          ]
        : []),
      "[Architecture overview](overview.md)",
    ],
  );
}

export function renderOutputs(graph: ArchitectureGraph) {
  const context = {
    schemaVersion: graph.schemaVersion,
    graph: `${OUTPUT_DIRECTORY}/graph.json`,
    subsystems: graph.subsystems,
    nodes: graph.nodes,
    edges: graph.edges.map(({ from, to, type, provenance, ...edge }) => ({
      from,
      to,
      type,
      provenance,
      ...("commands" in edge ? { commands: edge.commands } : {}),
    })),
  };
  const serialized = `${JSON.stringify(context)}\n`;
  if (Buffer.byteLength(serialized) > CONTEXT_MAX_BYTES) {
    throw new Error(`agent-context.json exceeds ${CONTEXT_MAX_BYTES} bytes`);
  }

  return new Map([
    ["graph.json", `${JSON.stringify(graph, null, 2)}\n`],
    ["agent-context.json", serialized],
    ["overview.md", renderOverview(graph)],
    ...Object.keys(graph.subsystems).map(
      (id) => [`${id}.md`, renderSubsystem(graph, id)] as const,
    ),
  ]);
}
